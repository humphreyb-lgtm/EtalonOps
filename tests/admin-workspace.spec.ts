import {test,expect} from '@playwright/test';
for(const width of [390,1440])test(`administration preserves user forms and the open MRF at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:1000});
 await page.goto('/?database=1&identity=admin');
 await expect(page.locator('main')).toHaveAttribute('aria-busy','false');
 const name=page.getByLabel('MRF name',{exact:true});
 await name.fill('Retain this unsaved MRF');
 await page.getByRole('button',{name:'Administration',exact:true}).click();
 const admin=page.getByRole('dialog',{name:'Administration',exact:true});
 await expect(admin).toBeVisible();
 await admin.screenshot({path:`artifacts/screenshots/${width}-administration-workspace.png`});
 await admin.getByRole('button',{name:'Users and access',exact:true}).click();
 await admin.getByRole('button',{name:'Register existing Microsoft user',exact:true}).click();
 await admin.getByLabel('User display name',{exact:true}).fill('Unsaved administrator entry');
 await admin.getByRole('button',{name:'AI usage',exact:true}).click();
 await expect(admin.getByRole('region',{name:'AI usage limits'})).toContainText('Disabled');
 await admin.getByRole('button',{name:'Users and access',exact:true}).click();
 await expect(admin.getByLabel('User display name',{exact:true})).toHaveValue('Unsaved administrator entry');
 await admin.getByRole('button',{name:'Product images',exact:true}).click();
 await expect(admin.getByRole('region',{name:'Product image administration'})).toBeVisible();
 await admin.getByRole('button',{name:'Job restrictions',exact:true}).click();
 await expect(admin.getByRole('heading',{name:'Job restrictions',exact:true})).toBeVisible();
 await admin.getByRole('button',{name:'Catalog and imports',exact:true}).click();
 await expect(admin.getByRole('button',{name:'Export catalog relationships',exact:true})).toBeVisible();
 await admin.getByText('Bulk materials, products, translations and image references',{exact:true}).click();
 await admin.getByLabel('Structured CSV contents',{exact:true}).fill('kind,data_json');
 await expect(admin.getByLabel('Structured CSV contents',{exact:true})).toHaveValue('kind,data_json');
 expect(await admin.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
 page.once('dialog',d=>d.dismiss()); await admin.getByRole('button',{name:'Return to MRF'}).click();await expect(admin).toBeVisible();
 page.once('dialog',d=>d.accept()); await admin.getByRole('button',{name:'Return to MRF'}).click();await expect(admin).not.toBeVisible();
 await expect(name).toHaveValue('Retain this unsaved MRF');
 await expect(page.getByRole('button',{name:'Administration',exact:true})).toBeFocused();
});
test('foreman does not receive administration entry points or user access data',async({page})=>{
 await page.goto('/?database=1&identity=foreman-one');await expect(page.locator('main')).toHaveAttribute('aria-busy','false');
 await expect(page.getByRole('button',{name:'Administration',exact:true})).toHaveCount(0);
 const session=await page.request.post('/api/dev/session',{data:{identity:'foreman-one'}});const {token}=await session.json();
 const response=await page.request.post('/api/admin/users/list',{headers:{authorization:`Bearer ${token}`},data:{page:1,text:''}});expect(response.status()).toBe(403);
});
test('administrator saves access changes through the workspace with retained history',async({page})=>{
 await page.goto('/?database=1&identity=admin');await page.getByRole('button',{name:'Administration',exact:true}).click();
 const admin=page.getByRole('dialog',{name:'Administration',exact:true});await admin.getByRole('button',{name:'Users and access',exact:true}).click();
 await admin.getByRole('button',{name:'Register existing Microsoft user',exact:true}).click();
 await admin.getByLabel('Microsoft object ID',{exact:true}).fill(crypto.randomUUID());await admin.getByLabel('User display name',{exact:true}).fill('Workspace registered foreman');
 await admin.getByLabel('Assign Northside Service Center',{exact:true}).check();await admin.getByLabel('Reason for access change',{exact:true}).fill('Register access through the dedicated administration workspace.');
 await admin.getByLabel("I reviewed this user's account status, role and project access.",{exact:true}).check();await admin.getByRole('button',{name:'Save user access',exact:true}).click();
 await expect(admin.getByRole('status')).toContainText('User access saved.');await admin.getByRole('button',{name:'Load user access history',exact:true}).click();
 await expect(admin.getByRole('region',{name:'User access history'})).toContainText('Register access through the dedicated administration workspace.');
});
