"""Build stable, code-owned design targets from literal application class names."""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parent.parent
classes=set()
for path in (root/'src').glob('*.tsx'):
 if path.name in ['AppearanceStudio.tsx','AppearanceWorkspace.tsx']:continue
 for names in re.findall(r'className=["\']([a-zA-Z0-9_ -]+)["\']',path.read_text()):
  classes.update(name for name in names.split() if re.fullmatch(r'[a-zA-Z][a-zA-Z0-9_-]*',name))
classes-= {'appearance-studio','sr-only','hidden','primary','button','active','selected','is-added','no-substitutions'}
(root/'src/appearance-components.ts').write_text('// Generated by scripts/build-appearance-components.py. Stable component class names only.\nexport const appearanceComponents='+json.dumps(sorted(classes),indent=1)+' as const;\n')
print(f'Registered {len(classes)} application component targets.')
